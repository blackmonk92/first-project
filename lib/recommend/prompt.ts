// 한국 사용자 대상 서비스라 KST 기준으로 month/day를 뽑아야 한국 자정 무렵
// 하루 어긋나는 사고가 안 생긴다. 서버 런타임이 UTC여도 안전.
function getKstParts(now: Date): { month: number; day: number } {
  const parts = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Seoul",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(now);
  const month = Number(parts.find((p) => p.type === "month")!.value);
  const day = Number(parts.find((p) => p.type === "day")!.value);
  return { month, day };
}

export function getSeasonKst(now: Date = new Date()): Season {
  const { month } = getKstParts(now);
  if (month === 7 || month === 8) return "한여름";
  if (month === 12 || month === 1 || month === 2) return "한겨울";
  return "봄·가을";
}

export function getTodayKst(now: Date = new Date()): string {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Seoul",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(now);
}

